package LibpgQuery::NodeSupport::Outfuncs;

# Generates the node output/input support shared by the JSON and Protobuf
# output formats and the Protobuf input format, as well as the Protobuf
# definition itself:
#
#   pg_query_enum_defs.c       - _enumToString / _enumToInt / _intToEnum helpers
#   pg_query_outfuncs_defs.c   - _out<Node> functions (WRITE_*_FIELD macro calls)
#   pg_query_outfuncs_conds.c  - dispatch cases for _outNode
#   pg_query_readfuncs_defs.c  - _read<Node> functions (READ_*_FIELD macro calls)
#   pg_query_readfuncs_conds.c - dispatch cases for _readNode
#   pg_query.proto             - Protobuf definition
#   pg_query_scan_tokens.h     - Public C enums for the scan token API
#   pg_query_scan_defs.c       - Name lookups for the scan token API enums
#
# The macros are defined by the including files (pg_query_outfuncs_json.c,
# pg_query_outfuncs_protobuf.c, pg_query_readfuncs_protobuf.c). Protobuf field
# numbers are assigned sequentially in field declaration order, so which fields
# are emitted (see outfuncs_skip_fields in overrides.pl) determines wire
# compatibility.

use strict;
