package LibpgQuery::NodeSupport::Outfuncs;

# Generates the node output/input support shared by the JSON and Protobuf
# output formats and the Protobuf input format, as well as the Protobuf
# definition itself:
#
#   pg_query_enum_defs.c       - _enumToString / _enumToInt / _intToEnum helpers
#   pg_query_outfuncs_defs.c   - _out<Node> functions (WRITE_*_FIELD macro calls)
#   pg_query_outfuncs_conds.c  - dispatch cases for _outNode
#   pg_query_readfuncs_defs.c  - _read<Node> functions (READ_*_FIELD macro calls)
#   pg_query_readfuncs_conds.c - dispatch cases for _readNode
#   pg_query.proto             - Protobuf definition
#
# The macros are defined by the including files (pg_query_outfuncs_json.c,
# pg_query_outfuncs_protobuf.c, pg_query_readfuncs_protobuf.c). Protobuf field
# numbers are assigned sequentially in field declaration order, so which fields
# are emitted (see outfuncs_skip_fields in overrides.pl) determines wire
# compatibility.

use strict;
use warnings FATAL => 'all';

use LibpgQuery::NodeSupport::Common
  qw(elem write_file node_fields parse_tree_nodes underscore);

my $HEADER =
  "// This file is autogenerated by ./scripts/generate_node_support.sh\n\n";

my @INT_TYPES = qw(int int16 int32 AttrNumber ParseLoc);
my @UINT_TYPES =
  qw(uint uint16 uint32 Index bits32 Oid SubTransactionId RelFileNumber);
my @UINT64_TYPES = qw(uint64 AclMode);
my @FLOAT_TYPES = qw(float double Cost Cardinality Selectivity);
my @BITMAPSET_TYPES = ('Bitmapset*', 'Relids');

# Value node types with hand-written support, appended to the Node oneof
my @VALUE_NODE_TYPES =
  qw(Integer Float Boolean String BitString List IntList OidList A_Const);

# Dispatch cases for the hand-written value node support
my $OUT_CONDS_PREAMBLE = <<'EOT';
case T_Integer:
  OUT_NODE(Integer, Integer, integer, INTEGER, Integer, integer);
  break;
case T_Boolean:
  OUT_NODE(Boolean, Boolean, boolean, BOOLEAN, Boolean, boolean);
  break;
case T_Float:
  OUT_NODE(Float, Float, float, FLOAT, Float, float_);
  break;
case T_String:
  OUT_NODE(String, String, string, STRING, String, string);
  break;
case T_BitString:
  OUT_NODE(BitString, BitString, bit_string, BIT_STRING, BitString, bit_string);
  break;
case T_List:
  OUT_NODE(List, List, list, LIST, List, list);
  break;
case T_IntList:
  OUT_NODE(IntList, IntList, int_list, INT_LIST, List, int_list);
  break;
case T_OidList:
  OUT_NODE(OidList, OidList, oid_list, OID_LIST, List, oid_list);
  break;
case T_A_Const:
  OUT_NODE(A_Const, AConst, a__const, A_CONST, A_Const, a_const);
  break;
EOT

